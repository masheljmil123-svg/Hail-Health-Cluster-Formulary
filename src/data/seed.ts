const catalogNote = (name: string) =>
  `Demonstration catalog record for ${name}. This is not an approved monograph and is not for clinical use.`;

function drug(partial: Omit<Drug, 'overview' | 'dosing' | 'restrictions' | 'safety' | 'monitoring' | 'compatibility' | 'references'> & Partial<Pick<Drug, 'overview'>>): Drug {
  return {
    overview: partial.overview ?? catalogNote(partial.genericName),
    dosing: '',
    restrictions: '',
    safety: '',
    monitoring: '',
    compatibility: '',
    references: '',
    ...partial,
  };
}

